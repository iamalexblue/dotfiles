-- ==========================================================================
-- 文件浏览器设置 (File Explorer Settings)
-- ==========================================================================
-- 设置 netrw（内置文件浏览器）的列表样式为树形
vim.cmd("let g:netrw_liststyle = 3")

local opt = vim.opt

-- ==========================================================================
-- 行号设置 (Line Numbers)
-- ==========================================================================
-- 显示相对行号，方便看到光标上下的行数
opt.relativenumber = true
-- 同时显示绝对行号
opt.number = true

-- ==========================================================================
-- 缩进设置 (Indentation)
-- ==========================================================================
-- Tab 宽度为 2 个空格
opt.tabstop = 2
-- 缩进宽度为 2 个空格
opt.shiftwidth = 2
-- 将 Tab 展开为空格
opt.expandtab = true
-- 自动继承当前行的缩进
opt.autoindent = true

-- ==========================================================================
-- 文本显示 (Text Display)
-- ==========================================================================
-- 关闭自动换行，代码不会因为超出宽度被折行
opt.wrap = false

-- ==========================================================================
-- 搜索设置 (Search Settings)
-- ==========================================================================
-- 搜索时忽略大小写
opt.ignorecase = true
-- 但如果搜索内容包含大写字母，则区分大小写
opt.smartcase = true

-- ==========================================================================
-- 光标显示 (Cursor Display)
-- ==========================================================================
-- 高亮当前行
opt.cursorline = true

-- ==========================================================================
-- 颜色设置 (Color Settings)
-- ==========================================================================
-- 开启真彩色支持（在 iterm2 或其他真彩色终端中使用）
opt.termguicolors = true
-- 强制使用深色背景
opt.background = "dark"
-- 固定显示符号列，防止文字跳动感
opt.signcolumn = "yes"

-- ==========================================================================
-- 退格键设置 (Backspace Settings)
-- ==========================================================================
-- 允许退格键在：缩进、行尾、插入模式起始位置 上工作
opt.backspace = "indent,eol,start"

-- ==========================================================================
-- 剪贴板设置 (Clipboard Settings)
-- ==========================================================================
-- 使用系统剪贴板作为默认寄存器（unnamedplus = + 寄存器）
opt.clipboard:append("unnamedplus")

-- ==========================================================================
-- 分屏设置 (Split Window Settings)
-- ==========================================================================
-- 垂直分屏时，新窗口在右侧
opt.splitright = true
-- 水平分屏时，新窗口在下方
opt.splitbelow = true

-- ==========================================================================
-- 交换文件设置 (Swap File Settings)
-- ==========================================================================
-- 关闭交换文件（减少磁盘写入，可设为 true 开启）
opt.swapfile = false
